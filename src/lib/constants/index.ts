// ============ HELPER FUNCTIONS ============
function uniqueByEmoji<T extends { emoji: string }>(list: T[]): T[] {
  const seen = new Set<string>();
  return list.filter((e) => (seen.has(e.emoji) ? false : (seen.add(e.emoji), true)));
}

export function getLocationEmojisByCategory(category: string) {
  return LOCATION_EMOJIS[category as keyof typeof LOCATION_EMOJIS] || [];
}

export function getItemsByCategory(category: string) {
  return ITEM_ICONS[category as keyof typeof ITEM_ICONS] || [];
}

/** Alle Ablageort-Emojis als eine Liste (ohne Doppelte) */
export function getAllLocationEmojis() {
  return uniqueByEmoji(Object.values(LOCATION_EMOJIS).flat());
}

/** Alle Gegenstands-Emojis als eine Liste (ohne Doppelte) */
export function getAllIcons() {
  return uniqueByEmoji(Object.values(ITEM_ICONS).flat());
}
